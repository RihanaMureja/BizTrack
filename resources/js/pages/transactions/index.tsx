function VisualDonut({
    title,
    data,
    colors,
    empty,
}: {
    title: string;
    data: Array<{ name: string; value: number }>;
    colors: string[];
    empty: string;
}) {
    return (
        <section className="rounded-xl border bg-card p-5 shadow-sm">
            <h2 className="font-semibold">{title}</h2>
            {data.length > 0 ? (
                <ResponsiveContainer width="100%" height={210}>
                    <PieChart>
                        <Pie
                            data={data}
                            dataKey="value"
                            nameKey="name"
                            innerRadius={48}
                            outerRadius={78}
                            paddingAngle={4}
                        >
                            {data.map((entry, index) => (
                                <Cell
                                    key={entry.name}
                                    fill={colors[index % colors.length]}
                                />
                            ))}
                        </Pie>
                        <Tooltip />
                    </PieChart>
                </ResponsiveContainer>
            ) : (
                <div className="mt-4 rounded-xl border border-dashed bg-muted/20 p-8 text-center text-sm text-muted-foreground">
                    {empty}
                </div>
            )}
        </section>
    );
}

function averageAmount(rows: Array<{ amount: string }>) {
    if (rows.length === 0) return 0;
    return rows.reduce((sum, row) => sum + Number(row.amount), 0) / rows.length;
}

